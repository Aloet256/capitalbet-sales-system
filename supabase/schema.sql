CREATE SCHEMA IF NOT EXISTS capitalbet;
REVOKE ALL ON SCHEMA capitalbet FROM PUBLIC;

CREATE TABLE IF NOT EXISTS capitalbet.config (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS capitalbet.branches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  pin_hash text NOT NULL,
  pin_cipher text NOT NULL
);

CREATE TABLE IF NOT EXISTS capitalbet.sessions (
  token_hash text PRIMARY KEY,
  role text NOT NULL CHECK (role IN ('admin', 'staff')),
  branch_id integer REFERENCES capitalbet.branches(id),
  expires_at bigint NOT NULL,
  CHECK ((role = 'staff') = (branch_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS capitalbet_sessions_by_branch ON capitalbet.sessions (branch_id);
CREATE INDEX IF NOT EXISTS capitalbet_sessions_by_expiry ON capitalbet.sessions (expires_at);

CREATE TABLE IF NOT EXISTS capitalbet.auth_attempts (
  key text PRIMARY KEY,
  tries integer NOT NULL CHECK (tries >= 0),
  expires_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS capitalbet_auth_attempts_by_expiry ON capitalbet.auth_attempts (expires_at);

CREATE TABLE IF NOT EXISTS capitalbet.entries (
  branch_id integer NOT NULL REFERENCES capitalbet.branches(id),
  kind text NOT NULL CHECK (kind IN ('slots', 'live')),
  day date NOT NULL,
  amounts jsonb NOT NULL CHECK (jsonb_typeof(amounts) = 'object'),
  net_balance bigint NOT NULL,
  revision integer NOT NULL CHECK (revision > 0),
  PRIMARY KEY (branch_id, kind, day)
);
CREATE INDEX IF NOT EXISTS capitalbet_entries_by_day ON capitalbet.entries (day);

CREATE TABLE IF NOT EXISTS capitalbet.notifications (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  payload jsonb NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  available_at bigint NOT NULL,
  lease_token uuid,
  lease_until bigint
);
CREATE INDEX IF NOT EXISTS capitalbet_notifications_by_availability ON capitalbet.notifications (available_at, id);

ALTER TABLE capitalbet.config ENABLE ROW LEVEL SECURITY;
ALTER TABLE capitalbet.branches ENABLE ROW LEVEL SECURITY;
ALTER TABLE capitalbet.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE capitalbet.auth_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE capitalbet.entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE capitalbet.notifications ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA capitalbet FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA capitalbet FROM PUBLIC;
